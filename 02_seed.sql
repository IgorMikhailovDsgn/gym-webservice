-- -----------------------------------------------------------------------------
--  Сверка счётчика с фактом.
--
--  visits_used — денормализация, и в тестовых данных легко разойтись с
--  реальными строками visits. Вместо ручного проставления пересчитываем
--  счётчик из фактических посещений: сид остаётся консистентным, даже если
--  выше добавить или убрать посещения.
-- -----------------------------------------------------------------------------
UPDATE tickets t
SET visits_used = COALESCE(v.cnt, 0)
FROM (
    SELECT ticket_id, count(*) AS cnt FROM visits GROUP BY ticket_id
) v
WHERE v.ticket_id = t.id;